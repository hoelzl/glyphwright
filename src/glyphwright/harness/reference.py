"""Generate the command reference from the tables that implement the commands.

The page is a derived view: the verb table in ``frontends/wire.py``, the
meta commands in ``harness/meta.py``, and the query paths in
``harness/query.py`` are the sources. Regenerate the committed page with::

    uv run python -m glyphwright.harness.reference

A test fails while the committed page differs from a fresh render.
"""

from __future__ import annotations

import sys
from pathlib import Path

from glyphwright.frontends.wire import VERBS
from glyphwright.harness import meta, query

REGENERATE = "uv run python -m glyphwright.harness.reference"
PAGE = Path("docs/knowledge/commands.md")

# Rejection reasons that belong to no single verb: (reason, when, hint).
GENERAL_REASONS: tuple[tuple[str, str, str], ...] = (
    (
        "wrong_mode",
        "the verb exists, but not in the active mode",
        "the verbs valid now",
    ),
    ("unknown_verb", "no mode knows the verb", "the verbs valid now"),
    ("defeated", "the player is defeated", "that only `look` remains"),
    (
        "unparsable",
        "the line is not a command at all (frontends)",
        "the verbs valid now",
    ),
    (
        "harness_disabled",
        "a meta command without `--harness` (frontends)",
        "how to enable meta commands",
    ),
    (
        "unknown_meta",
        "a `:` line that is not a meta command (frontends)",
        "the meta commands' usage",
    ),
)


def _code(items: tuple[str, ...]) -> str:
    return ", ".join(f"`{item}`" for item in items) or "none"


def render() -> str:
    """The full text of the command reference."""
    lines = [
        "# Commands",
        "",
        "Every command, rejection, meta command, and query path the engine",
        "accepts, generated from the code that implements them. Read it when",
        "you play a session, drive the JSONL stream, or write a verifier.",
        "",
        f"<!-- GENERATED by `{REGENERATE}` from the verb table, the meta commands,",
        "     and the query paths; do not edit. -->",
        "",
        "## Contents",
        "",
        "- [Game commands](#game-commands)",
        "- [Rejections](#rejections)",
        "- [Meta commands](#meta-commands)",
        "- [Query paths](#query-paths)",
        "",
        "## Game commands",
        "",
        "The grammar in every frame lists which of these are valid right now,",
        "with one domain per argument. `move` offers every exit, walls included:",
        "a blocked move still spends the turn and says why. Item commands offer",
        "only items the command would work on.",
        "",
        "| Command | What it does | Spends a turn | Events |",
        "|---|---|---|---|",
    ]
    lines.extend(
        f"| `{spec.usage()}` | {spec.summary} | "
        f"{'yes' if spec.spends_turn else 'no'} | {_code(spec.events)} |"
        for spec in VERBS
    )
    lines += [
        "",
        "## Rejections",
        "",
        "A refused command comes back as a rejection with a reason and a hint;",
        "nothing changes and no turn passes.",
        "",
        "| Reason | When | Hint |",
        "|---|---|---|",
    ]
    lines.extend(
        f"| `{spec.reason}` | `{spec.verb}` names something not on offer | "
        f'"{spec.options_hint}: …", or "{spec.empty_hint}" |'
        for spec in VERBS
        if spec.reason is not None
    )
    lines.extend(
        f"| `{reason}` | {when} | {hint} |" for reason, when, hint in GENERAL_REASONS
    )
    lines += [
        "",
        "## Meta commands",
        "",
        "Available with `--harness`; they never pass a turn.",
        "",
        "| Command | What it does |",
        "|---|---|",
    ]
    lines.extend(f"| `{command}` | {what} |" for command, what in meta.COMMANDS)
    lines += [
        "",
        "## Query paths",
        "",
        "`<id>` is an entity id and `<stat>` a stat name, such as",
        "`player.stats.atk`.",
        "",
        "| Path | Answer |",
        "|---|---|",
    ]
    lines.extend(f"| `{path}` | {answer} |" for path, answer in query.PATHS)
    lines += ["", "| Error | When |", "|---|---|"]
    lines.extend(f"| `{error}` | {when} |" for error, when in query.ERRORS)
    return "\n".join(lines) + "\n"


def write(page: Path = PAGE) -> bool:
    """Rewrite the page; return whether it changed."""
    text = render()
    if page.is_file() and page.read_text(encoding="utf-8") == text:
        return False
    page.write_text(text, encoding="utf-8", newline="\n")
    return True


if __name__ == "__main__":
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else PAGE
    if write(target):
        print(f"wrote {target.as_posix()}")
