"""JSON Schema generation for the wire types.

Schemas are generated from the encoders' shape and committed under ``schemas/``.
A test asserts the generated schemas match the committed files, so the contract
cannot drift silently; a schema change is deliberate, reviewed, and versioned by
bumping the tag (decision 0002).

Regenerate the committed files with::

    uv run python -m glyphwright.harness.schema

Generation is hand-rolled deliberately: the wire types are ours and stay simple,
and the engine carries no dependencies.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from glyphwright.frontends.wire import (
    EVENT_SCHEMA,
    FRAME_SCHEMA,
    QUERY_SCHEMA,
    REJECTION_SCHEMA,
)
from glyphwright.harness.fingerprint import SESSION_SCHEMA
from glyphwright.kernel.state import BATTLE_OUTCOMES

REGENERATE = "uv run python -m glyphwright.harness.schema"
_DRAFT = "https://json-schema.org/draft/2020-12/schema"
_COMMENT = f"GENERATED by `{REGENERATE}`; do not edit."
_STRING: dict[str, Any] = {"type": "string"}
_INTEGER: dict[str, Any] = {"type": "integer"}
_PAIR: dict[str, Any] = {
    "type": "array",
    "items": _INTEGER,
    "minItems": 2,
    "maxItems": 2,
}


def _object(
    properties: dict[str, Any], *, required: list[str] | None = None
) -> dict[str, Any]:
    return {
        "type": "object",
        "properties": properties,
        "required": sorted(required if required is not None else properties),
        "additionalProperties": False,
    }


def _array(items: dict[str, Any]) -> dict[str, Any]:
    return {"type": "array", "items": items}


def _document(schema_id: str, title: str, body: dict[str, Any]) -> dict[str, Any]:
    return {
        "$schema": _DRAFT,
        "$id": schema_id,
        "$comment": _COMMENT,
        "title": title,
    } | body


def session_schema() -> dict[str, Any]:
    return _document(
        SESSION_SCHEMA,
        "GlyphWright session header",
        _object(
            {
                "schema": {"const": SESSION_SCHEMA},
                "engine": _STRING,
                "rules": _INTEGER,
                "pack": _STRING,
                "seed": _INTEGER,
                "harness": {"type": "boolean"},
            }
        ),
    )


def frame_schema() -> dict[str, Any]:
    cell = _object(
        {"ground": _STRING, "fixture": _STRING, "actor": _STRING},
        required=["ground"],
    )
    grid = _object(
        {
            "kind": {"const": "grid"},
            "area": _STRING,
            "origin": _PAIR,
            "cells": _array(_array(cell)),
            "legend": {"type": "object", "additionalProperties": _STRING},
        }
    )
    menu = _object(
        {"kind": {"const": "menu"}, "area": _STRING, "combatants": _array(_STRING)}
    )
    viewport = {"oneOf": [grid, menu]}
    actor = _object({"id": _STRING, "name": _STRING, "hp": _PAIR, "at": _STRING})
    item = _object(
        {"id": _STRING, "name": _STRING, "slot": _STRING}, required=["id", "name"]
    )
    commands = _object(
        {"verbs": {"type": "object", "additionalProperties": _array(_array(_STRING))}}
    )
    return _document(
        FRAME_SCHEMA,
        "GlyphWright semantic frame",
        _object(
            {
                "schema": {"const": FRAME_SCHEMA},
                "turn": _INTEGER,
                "mode": _STRING,
                "viewport": viewport,
                "actors": _array(actor),
                "messages": _array(_STRING),
                "inventory": _array(item),
                "prompt": _object({"kind": _STRING}),
                "commands": commands,
            }
        ),
    )


# One branch per event type, so each type's fields are checked exactly.
# v0 finding H1: one flat object allowed any field on any event.
_EVENT_FIELDS: dict[str, tuple[dict[str, Any], list[str] | None]] = {
    "Moved": (
        {
            "actor": _STRING,
            "origin": _STRING,
            "destination": _STRING,
            "exit": _STRING,
        },
        None,
    ),
    "MoveBlocked": (
        {"actor": _STRING, "origin": _STRING, "exit": _STRING, "reason": _STRING},
        None,
    ),
    "TurnAdvanced": ({"turn_now": _INTEGER, "rng": _STRING}, ["turn_now"]),
    "ItemAcquired": ({"actor": _STRING, "item": _STRING, "origin": _STRING}, None),
    "ItemUsed": ({"actor": _STRING, "item": _STRING, "target": _STRING}, None),
    "ItemEquipped": (
        {"actor": _STRING, "item": _STRING, "slot": _STRING, "replaced": _STRING},
        ["actor", "item", "slot"],
    ),
    "Healed": ({"target": _STRING, "amount": _INTEGER, "source": _STRING}, None),
    "Provoked": ({"actor": _STRING}, None),
    "DamageDealt": (
        {"source": _STRING, "target": _STRING, "amount": _INTEGER},
        None,
    ),
    "AttackMissed": ({"source": _STRING, "target": _STRING}, None),
    "ActorDied": ({"actor": _STRING}, None),
    "Defeated": ({"actor": _STRING}, None),
    "ModePushed": ({"mode": _STRING, "initiative": _array(_STRING)}, None),
    "ModePopped": (
        {"mode": _STRING, "outcome": {"enum": list(BATTLE_OUTCOMES)}},
        None,
    ),
    "FleeFailed": ({"actor": _STRING}, None),
}


def event_schema() -> dict[str, Any]:
    common = {"schema": {"const": EVENT_SCHEMA}, "turn": _INTEGER}
    branches = []
    for event_type, (fields, required) in _EVENT_FIELDS.items():
        properties = common | {"type": {"const": event_type}} | fields
        branches.append(
            _object(
                properties,
                required=[*common, "type", *(required or fields)],
            )
        )
    return _document(EVENT_SCHEMA, "GlyphWright event", {"oneOf": branches})


def rejection_schema() -> dict[str, Any]:
    return _document(
        REJECTION_SCHEMA,
        "GlyphWright rejection",
        _object(
            {
                "schema": {"const": REJECTION_SCHEMA},
                "turn": _INTEGER,
                "command": _STRING,
                "reason": _STRING,
                "hint": _STRING,
            }
        ),
    )


def query_schema() -> dict[str, Any]:
    return _document(
        QUERY_SCHEMA,
        "GlyphWright query result",
        _object(
            {
                "schema": {"const": QUERY_SCHEMA},
                "path": _STRING,
                "value": {},
                "explanation": _array(
                    _object(
                        {
                            "source": _STRING,
                            "op": {"enum": ["base", "add", "mul", "clamp"]},
                            "value": _INTEGER,
                            "running": _INTEGER,
                        }
                    )
                ),
                "error": _STRING,
            },
            required=["schema", "path"],
        ),
    )


def _filename(schema_id: str) -> str:
    """``glyphwright.frame/1`` is committed as ``glyphwright.frame.v1.json``."""
    name, _, version = schema_id.partition("/")
    return f"{name}.v{version}.json"


def all_schemas() -> dict[str, dict[str, Any]]:
    """Every wire schema, keyed by the filename it is committed under."""
    schemas = (
        session_schema(),
        frame_schema(),
        event_schema(),
        rejection_schema(),
        query_schema(),
    )
    return {_filename(schema["$id"]): schema for schema in schemas}


def render(schema: dict[str, Any]) -> str:
    """Canonical on-disk form, so the committed diff is stable."""
    return json.dumps(schema, indent=2, sort_keys=True) + "\n"


def write(directory: Path) -> list[str]:
    """Rewrite the committed schemas; return the files that changed or went."""
    changed = []
    directory.mkdir(exist_ok=True)
    wanted = all_schemas()
    for stale in sorted(directory.glob("*.json")):
        if stale.name not in wanted:
            stale.unlink()
            changed.append(stale.name)
    for filename, schema in wanted.items():
        target = directory / filename
        text = render(schema)
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            target.write_text(text, encoding="utf-8", newline="\n")
            changed.append(filename)
    return changed


if __name__ == "__main__":
    for name in write(Path(sys.argv[1] if len(sys.argv) > 1 else "schemas")):
        print(f"wrote schemas/{name}")
